"""Builds design-system/components/onboarding.js and onboarding.css.
The CSS for MissionCard and MissionRow is taken from tools/src/onboarding.html so the prototype and the
components cannot drift apart. Run from the repo root:  python3 tools/build_onboarding_components.py"""
import base64, os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(root, 'tools', 'assets', 'onboarding')
def uri(name):
    mime = {'png': 'image/png', 'svg': 'image/svg+xml'}[name.rsplit('.', 1)[1]]
    return 'data:%s;base64,%s' % (mime, base64.b64encode(open(os.path.join(A, name), 'rb').read()).decode())
js = open(os.path.join(root, 'tools', 'src', 'onboarding-components.src.js')).read()
for k, n in {'COIN': 'coin.svg', 'FOX': 'fox.png', 'HAND': 'hand.png', 'PILE': 'pile.png', 'CLOCK': 'clock.svg'}.items():
    js = js.replace('__%s__' % k, uri(n))
open(os.path.join(root, 'design-system', 'components', 'onboarding.js'), 'w').write(js)

proto = open(os.path.join(root, 'tools', 'src', 'onboarding.html')).read()
